CREATE TABLE DXAPI_DATASOURCE_M (
  DATA_SRC_ID VARCHAR2(20 BYTE) NOT NULL,
  DATA_SRC_NM VARCHAR2(100 CHAR) NOT NULL,
  DB_TYPE_DVCD VARCHAR2(10 BYTE) NOT NULL,
  JDBC_URL VARCHAR2(500 BYTE) NOT NULL,
  DB_USER_ID VARCHAR2(50 BYTE) NOT NULL,
  DB_ENC_PW VARCHAR2(500 BYTE) NOT NULL,
  MINI_POOL_CNT NUMBER(3) DEFAULT 5 NOT NULL,
  MAX_POOL_CNT NUMBER(3) DEFAULT 20 NOT NULL,
