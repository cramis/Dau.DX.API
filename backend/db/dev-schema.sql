  PW_HASH VARCHAR2(100 BYTE) NOT NULL,
  USER_NM VARCHAR2(50 CHAR) NOT NULL,
  HP_NO VARCHAR2(20 BYTE) NOT NULL,
  EMAIL VARCHAR2(100 BYTE) NOT NULL,
